const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
test('receipt UI saves, posts, attaches, confirms and links source',async()=>{
 const fixture=JSON.parse(fs.readFileSync(process.env.ERP_RECEIVING_FIXTURE || 'outputs/purchase-receipt-return-import/browser-fixture.json','utf8'));
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try {
 const page=await browser.newPage({viewport:{width:1366,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(token=>localStorage.setItem('erp-session',JSON.stringify({token,username:'flow-admin',permissions:['*']})),fixture.token);
 await page.goto(process.env.ERP_RECEIVING_FRONTEND_URL || 'http://127.0.0.1:5193');
 await page.getByRole('button',{name:'采购管理',exact:true}).click();
 await page.locator('.subnav').getByRole('button',{name:'收货单',exact:true}).click();
 await page.getByRole('button',{name:'新增',exact:true}).click();
 await page.getByRole('button',{name:'检索供应商',exact:true}).click();
 const lookup=page.getByRole('dialog',{name:'供应商查询'});
 await lookup.getByRole('button',{name:/RC-S/}).click();await lookup.getByRole('button',{name:'确认',exact:true}).click();
 await page.getByLabel('供应商送货单号',{exact:true}).fill('BROWSER-DN');
 await page.getByRole('button',{name:'工具：按采购单生成收货明细',exact:true}).click();
 const gen=page.getByRole('dialog',{name:'按采购单生成收货明细'});
 await gen.getByRole('button',{name:'查询',exact:true}).click();
 await gen.getByLabel('选择 RC-PO/10',{exact:true}).check();
 await gen.getByRole('button',{name:'生成',exact:true}).click();
 await page.getByLabel('正式数量 第1行',{exact:true}).fill('4');
 await page.getByLabel('备品数量 第1行',{exact:true}).fill('1');
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.getByRole('status').filter({hasText:'单据已保存'}).waitFor();
 await page.screenshot({path:'outputs/purchase-receipt-return-import/browser-receipt.png',fullPage:true});
 await page.getByRole('button',{name:'审核',exact:true}).click();
 await page.getByRole('button',{name:'回单确认',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'上传'}).waitFor();
 await page.getByLabel('上传回单附件').setInputFiles({name:'signed.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\n signed')});
 await page.getByRole('button',{name:'上传附件',exact:true}).click();
 await page.getByRole('status').filter({hasText:'附件已上传'}).waitFor();
 await page.getByRole('button',{name:'回单确认',exact:true}).click();
 await page.getByText('已审核 · 回单已确认',{exact:true}).waitFor();
 await page.screenshot({path:'outputs/purchase-receipt-return-import/browser-confirmed.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await page.getByRole('button',{name:'预览',exact:true}).click();
 await page.locator('.rc-print-sheet').waitFor();
 await page.emulateMedia({media:'print'});
 assert.equal(await page.locator('.rc-print-sheet').isVisible(),true);
 await page.pdf({path:'outputs/purchase-receipt-return-import/receipt-print.pdf',format:'A4',landscape:true,printBackground:true});
 await page.screenshot({path:'outputs/purchase-receipt-return-import/browser-print.png',fullPage:true});
 await page.emulateMedia({media:'screen'});
 await page.getByRole('button',{name:'关闭预览',exact:true}).click();
 await page.getByRole('button',{name:'RC-PO',exact:true}).click();
 await page.getByRole('heading',{name:/采购单/}).waitFor();
 await page.locator('.subnav').getByRole('button',{name:'采购退货',exact:true}).click();
 await page.getByRole('button',{name:'新增',exact:true}).click();
 await page.getByRole('button',{name:'检索供应商',exact:true}).click();
 await lookup.getByRole('button',{name:/RC-S/}).click();await lookup.getByRole('button',{name:'确认',exact:true}).click();
 await page.getByLabel('退货暂存仓 *',{exact:true}).selectOption({label:'FG01 成品仓'});
 await page.getByLabel('备注',{exact:true}).fill('浏览器验收退货');
 await page.getByRole('button',{name:'选择可退采购明细',exact:true}).click();
 const returns=page.getByRole('dialog',{name:'选择可退明细'});
 await returns.getByRole('button',{name:'查询',exact:true}).click();
 await returns.getByLabel('选择 RC-PO/10',{exact:true}).check();
 await returns.getByRole('button',{name:'生成',exact:true}).click();
 await page.getByLabel('正式数量 第1行',{exact:true}).fill('1');
 await page.getByLabel('备品数量 第1行',{exact:true}).fill('0');
 await page.getByLabel('不良原因 第1行',{exact:true}).fill('尺寸超差');
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.getByRole('status').filter({hasText:'单据已保存'}).waitFor();
 await page.getByRole('button',{name:'审核',exact:true}).click();
 await page.getByRole('status').filter({hasText:'操作已完成'}).waitFor();
 await page.screenshot({path:'outputs/purchase-receipt-return-import/browser-return.png',fullPage:true});
 assert.deepEqual(errors,[]);
 } finally {await browser.close()}
});
